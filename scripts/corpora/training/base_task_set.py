"""Conversational planning prompts for probing LLM planning-horizon representations.

The task metadata is intended for downstream controls: analyses can separate
time-horizon effects from task family, difficulty, domain, planning style,
stakes, urgency, reversibility, and how far the consequences reach.

Every task uses all supported time units and the same value grid, from one
second to thirty millennia. Task metadata never restricts the duration
range, including when the requested duration is implausible for the task.
In particular `temporal_horizon` is the duration the *author* expects the task
to take. It is a hand label written before any activation was measured, never a
model output, and nothing in the pipeline fits on it or uses it to choose which
horizons a task is crossed with; it exists so a recovered readout can be checked
against an independent expectation.

The set is 100 tasks in two halves, distinguished by `source_set`. The 50
`original` tasks are the ones the stated corpora have always carried, with
their wording frozen so cached activations stay valid. The 50
`continuum_expansion` tasks fill cells the original 50 leave empty - most
importantly the off-diagonal ones where stakes and duration disagree, such as
existential stakes resolved in seconds or negligible stakes pursued for
generations, because those are the cells that identify a stakes effect apart
from a duration effect.

`stakes` is an ordered ten-level scale; `stakes_score` is its integer position
and is derived from `stakes` rather than labelled separately, so the two can
never disagree.
"""



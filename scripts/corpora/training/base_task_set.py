# Domains are open-ended - a new task may need a domain no earlier task used - so
# they are collected from the table below rather than fixed up front. Subdomains
# are finer still and are unique per task.
_VOCABULARIES = {
    "source_set": SOURCE_SETS,
    "complexity": COMPLEXITY_LEVELS,
    "difficulty": COMPLEXITY_LEVELS,
    "planning_type": PLANNING_TYPES,
    "stakes": STAKES_LEVELS,
    "agency": AGENCY_LEVELS,
    "temporal_horizon": TEMPORAL_HORIZONS,
    "affected_scope": AFFECTED_SCOPES,
    "urgency": URGENCY_LEVELS,
    "reversibility": REVERSIBILITY_LEVELS,
    "uncertainty": UNCERTAINTY_LEVELS,
    "coordination_load": COORDINATION_LOADS,
    "scenario_type": SCENARIO_TYPES,
    "scenario_realism": SCENARIO_REALISM,
    "primary_consequence": PRIMARY_CONSEQUENCES,
}


def validate_task_metadata(task: str, config: dict[str, object]) -> None:
    """Reject any label outside its vocabulary, so a typo cannot reach an analysis."""
    for field, allowed in _VOCABULARIES.items():
        if config[field] not in allowed:
            raise ValueError(f"Task {task!r}: {field}={config[field]!r} is not one of "
                             f"{allowed}")
    if not str(config["stakes_rationale"]).strip():
        raise ValueError(f"Task {task!r}: stakes_rationale must say why the stakes "
                         f"label was chosen")



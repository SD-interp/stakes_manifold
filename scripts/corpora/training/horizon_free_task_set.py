"""The task set used by the horizon-free corpora, decoupled from the stated ones.

The stated corpora cross every task with ten units and nine values, so their size
grows as tasks x units x values x templates and adding a task there costs thousands
of prompts. The horizon-free corpora emit exactly one prompt per (task, template),
so a task costs only as many prompts as there are horizon-free templates. The task
prior is estimated entirely from horizon-free prompts, and its sample size is the
number of *tasks* rather than the number of prompts, so this module exists to let
the control condition carry a much larger task set than the calibration corpora.

`base_task_set.tasks` remains the stated-corpus task set and is included
here unchanged as a subset, so priors for those tasks stay comparable with earlier
runs and the readout is still applied to the tasks it was calibrated on.

Task metadata reuses the stated schema exactly, down to the vocabularies and the
`_task` constructor imported from `base_task_set`, so every task in
either module carries the same fields and the same labels mean the same thing.
The three fields that most often get conflated are kept apart on purpose:
`agency` is who has to act, `affected_scope` is who bears the consequence, and
`temporal_horizon` is how long the author expects the task to take. That last one
is a hand label written before any activation was measured, never a model output,
and nothing in the pipeline fits on it; it exists so a recovered prior can be
checked against an independent expectation.

The tasks below are chosen to break the confound between stakes and duration that
the stated set carries. Stakes and duration are correlated in the world, so a task
set sampled naturally cannot separate them; the table deliberately fills the
off-diagonal cells - existential stakes resolved in seconds, negligible stakes
pursued for generations - because those are the cells that identify a stakes
effect apart from a duration effect. The expansion spans all eight duration bands,
and the stakes column is swept within each band.

The tasks are written as a table rather than as one keyword call each. At this row
count the table is what makes the design legible: the stakes and horizon columns
line up down the page, so a gap in the crossing is visible by reading a column
rather than by running an analysis.
"""


